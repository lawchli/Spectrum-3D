export const LANGS = ['zh', 'en'];
let lang = 'zh';

export function defaultLang() {
  return (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function getLang() { return lang; }

export function t(key, vars) {
  const text = STRINGS[lang][key] ?? STRINGS.zh[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : text;
}

// Switches language and rewrites every element marked with data-i18n.
export function setLang(next) {
  lang = STRINGS[next] ? next : 'zh';
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-tip]')) {
    el.dataset.tip = t(el.dataset.i18nTip);
    el.setAttribute('aria-label', el.dataset.tip);
  }
  for (const el of document.querySelectorAll('[data-i18n-label]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nLabel));
    el.title = t(el.dataset.i18nLabel);
  }
}
